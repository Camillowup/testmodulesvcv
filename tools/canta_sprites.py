for name, pal, rows in SINGERS:
    assert len(rows) == 21, name
    for i, r in enumerate(rows):
        assert len(r) == 16, (name, i, r)
        for c in r:
            assert c == "." or c in pal or c in SKIN, (name, i, c)
    assert "M" in rows[10], name


def palette(pal):
    d = dict(SKIN)
    d.update(pal)
    return d


def svg(x, y, k, i, mouth_open=True):
    """Singer i as SVG rects at (x, y), k px per pixel (for the preview)."""
    name, pal, rows = SINGERS[i]
    pal = palette(pal)
    s = []
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch == ".":
                continue
            col = pal[ch]
            if ch == "M" and mouth_open:
                col = pal["E"]
            s.append(f'<rect x="{x + c * k:.2f}" y="{y + r * k:.2f}" width="{k + 0.05:.2f}" height="{k + 0.05:.2f}" fill="{col}"/>')
    if mouth_open:
        c = rows[10].index("M")
        s.append(f'<rect x="{x + (c + 0.25) * k:.2f}" y="{y + 10.55 * k:.2f}" width="{1.5 * k:.2f}" height="{0.45 * k:.2f}" fill="#ff8fa3"/>')
    return "".join(s)


def header():
    """src/canta/CantaSprites.hpp: per singer its name, 21 rows and the colour of each letter."""
    L = ["// Generated by tools/canta_panel.py from tools/canta_sprites.py - do not edit",
         "// CANTA's singers: own pixel art (16 x 21), one per language (JAPANESE KIKO, ANIMAL MOMO, SCAT NANA, VOWELS SORA).",
         "#pragma once", "#include <cstdint>", "namespace canta_sprites {", "struct Singer {", "\tconst char* name;",
         "\tconst char* rows[21];", "\tconst char* keys;", "\tuint32_t colors[16];", "};", "static const Singer SINGERS[4] = {"]
    for name, pal, rows in SINGERS:
        p = palette(pal)
        keys = "".join(p.keys())
        cols = ", ".join("0x" + p[k][1:] for k in keys)
        L.append(f'\t{{"{name}", {{' + ", ".join(f'"{r}"' for r in rows) + f'}}, "{keys}", {{{cols}}}}},')
    L += ["};", "}  // namespace canta_sprites", ""]
    return "\n".join(L)
