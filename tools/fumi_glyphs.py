#!/usr/bin/env python3
"""FUMI's Japanese glyphs -> src/fumi/FumiGlyphs.hpp: the outlines of the few kanji and kana FUMI shows (the six
instruments' names and readings, 本数's 水 and 本, 三, 颪), from Noto Sans CJK JP Bold (SIL OFL 1.1, licenses/), as
path commands in em units (y up), so Rack draws them with NanoVG and no CJK font is shipped.

  tools/fumi_glyphs.py [FONT.ttc]
"""
import os
import sys

from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTCollection

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEXT = "爪音響名残箜篌拍子木魚" + "つめおとひびきなごりくごひょうしぎもくぎょ" + "水本三颪"
FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc"

coll = TTCollection(FONT)
font = next(f for f in coll.fonts if "JP" in f["name"].getDebugName(1))
gs, cmap, upm = font.getGlyphSet(), font.getBestCmap(), font["head"].unitsPerEm
chars = sorted(set(TEXT))
out = ["// Generated by tools/fumi_glyphs.py - do not edit",
       f"// Glyph outlines from {font['name'].getDebugName(4)} (SIL Open Font License 1.1: licenses/OFL-NotoSansCJK.txt).",
       "// Per glyph: its code point, its advance, and commands (0 move, 1 line, 2 cubic, 3 quad, 4 close, 5 the contour just",
       "// closed is a hole) with points",
       "// in em units, y up.", "#pragma once", "#include <cstdint>", "namespace fumi_glyphs {",
       "struct Glyph { uint32_t cp; float adv; int n; const float* d; };"]
names = []
for ch in chars:
    g = cmap[ord(ch)]
    pen = RecordingPen()
    gs[g].draw(pen)
    d, poly = [], []
    for op, pts in pen.value:
        poly += [p for p in pts]
        if op == "moveTo":
            poly = [pts[0]]
            d += [0, *pts[0]]
        elif op == "lineTo":
            d += [1, *pts[0]]
        elif op == "curveTo":
            for i in range(0, len(pts) - 2, 3):
                d += [2, *pts[i], *pts[i + 1], *pts[i + 2]]
        elif op == "qCurveTo":
            for i in range(len(pts) - 1):
                p1, p2 = pts[i], pts[i + 1] if i + 1 == len(pts) - 1 else (
                    ((pts[i][0] + pts[i + 1][0]) / 2, (pts[i][1] + pts[i + 1][1]) / 2))
                d += [3, *p1, *p2]
        elif op in ("closePath", "endPath"):
            area = sum(poly[i][0] * poly[(i + 1) % len(poly)][1] - poly[(i + 1) % len(poly)][0] * poly[i][1]
                       for i in range(len(poly)))
            d += [4] if area <= 0 else [4, 5]    # outlines run clockwise (y up): a counter-clockwise contour is a hole
    nm = f"G{ord(ch):X}"
    names.append((ord(ch), gs[g].width / upm, len(d), nm))
    vals, k = [], 0
    while k < len(d):
        op = d[k]
        vals.append(str(op))
        cnt = {0: 2, 1: 2, 2: 6, 3: 4, 4: 0, 5: 0}[op]
        vals += ["%.4g" % (v / upm) for v in d[k + 1:k + 1 + cnt]]
        k += 1 + cnt
    out.append(f"static const float {nm}[] = {{{','.join(vals)}}};")
out.append(f"static const Glyph GLYPHS[{len(names)}] = {{" +
           ", ".join(f"{{0x{cp:X}u, {adv:.4f}f, {n}, {nm}}}" for cp, adv, n, nm in names) + "};")
out.append(f"static const int NGLYPHS = {len(names)};")
out += ["}  // namespace fumi_glyphs", ""]
open(os.path.join(ROOT, "src", "fumi", "FumiGlyphs.hpp"), "w").write("\n".join(out))
print("written: src/fumi/FumiGlyphs.hpp,", len(names), "glyphs")
