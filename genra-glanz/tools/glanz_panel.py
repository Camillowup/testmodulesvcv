#!/usr/bin/env python3
"""The panel of GENRA GLANZ (music visuals) in the GENRA look (tools/gpanel.py).

Usage:  glanz_panel.py real           -> res/Glanz.svg (text as paths) + src/GlanzLayout.hpp
        glanz_panel.py preview OUT.png
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gpanel  # noqa: E402

SPEC = dict(
    name="GLANZ", sub="GENRA · MUSIC VISUALS", subshort="VISUALS", acc="#8fd3ff", preset="01  SPECTRUM RING", hp=40,
    rows=[[
        dict(title="REACT", cols=[[("knob", "AMOUNT", "AMOUNT")], [("knob", "SMOOTH", "SMOOTH")], [("knob", "DECAY", "DECAY")]]),
        dict(title="LOOK", cols=[[("small", "SPEED", "SPEED")], [("small", "COLOR", "COLOR")], [("small", "TRAILS", "TRAILS")],
                                 [("small", "ZOOM", "ZOOM")], [("small", "GLOW", "GLOW")]]),
        dict(title="TRACKS", cols=[[("button", "T0", "DRUMS")], [("button", "T1", "BASS")], [("button", "T2", "MELODY")],
                                   [("button", "T3", "PADS")]]),
        dict(title="SCENE", cols=[[("small", "AUTO", "AUTO BARS")], [("button", "FREEZE", "FREEZE")], [("button", "NEXT", "NEXT")]]),
    ]],
    strip=[("IN_L", "L"), ("IN_R", "R")], sync=[("IN_T0", "DRUMS"), ("IN_T1", "BASS"), ("IN_T2", "MELODY"), ("IN_T3", "PADS")],
    cvs=[[("CV_SCENE", "SCENE"), ("CV_COLOR", "COLOR"), ("CV_SPEED", "SPEED"), ("CV_ZOOM", "ZOOM"), ("CV_AMOUNT", "AMOUNT"),
          ("TRIG_NEXT", "NEXT"), ("TRIG_FREEZE", "FREEZE")]],
    jackrows=2)

p = gpanel.build(SPEC)
if not gpanel.preview(p, "Glanz"):
    open(os.path.join(gpanel.ROOT, "res", "Glanz.svg"), "w").write(gpanel.svg(p))
    hdr = ["// Generated by tools/glanz_panel.py - do not edit", "// Rack pixels (1 HP = 15 px).", "#pragma once",
           gpanel.layout(p, None, "glanzl"), ""]
    open(os.path.join(gpanel.ROOT, "src", "GlanzLayout.hpp"), "w").write("\n".join(hdr))
    print(f"Glanz: {p.hp} HP, written res/Glanz.svg src/GlanzLayout.hpp")
