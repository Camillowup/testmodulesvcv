int stylesInEra(int era, int* out, int max) {
	int n = 0;
	for (int i = 0; i < NUM_STYLES; i++)
		if (STYLES[i].era == era) {
			if (out && n < max)
				out[n] = i;
			n++;
		}
	return n;
}

int styleIndexInEra(int style) {
	int n = 0;
	for (int i = 0; i < style && i < NUM_STYLES; i++)
		if (STYLES[i].era == STYLES[style].era)
			n++;
	return n;
}

