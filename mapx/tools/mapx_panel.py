#!/usr/bin/env python3
"""The panel of GENRA MAP-X (MIDI mapper for GENRA) in the GENRA look (tools/gpanel.py). No jacks.

Usage:  mapx_panel.py real           -> res/MapX.svg (text as paths) + src/MapXLayout.hpp
        mapx_panel.py preview OUT.png
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gpanel  # noqa: E402

SPEC = dict(
    name="MAP-X", sub="GENRA · MIDI MAPPER", subshort="GENRA · MAP", acc="#7b6cff", hp=12, nojacks=True,
    rows=[[
        dict(title="SETUP",
             fields=[[("PRESETF", "MIDI MIX+MPD 218", "MAP")], [("DEV0F", "MIDI MIX", "IN 1")], [("DEV1F", "MPD 218", "IN 2")]]),
    ], [
        dict(title="MAP",
             cols=[[("button", "LEARN", "LEARN")], [("button", "CLEAR", "CLEAR", "plain")], [("button", "UNDO", "UNDO", "plain")]],
             lamps=[("MODE", "", ["ONCE", "ON/OFF", "HOLD", "STEP"])]),
    ]])

p = gpanel.build(SPEC)
if len(sys.argv) > 1 and sys.argv[1] == "preview":
    # what the display shows (only in the preview)
    x, y, w, h = next((cx, cy, kw["w"], kw["h"]) for k, n, cx, cy, kw in p.comps if n == "INFO")
    T = lambda *a, **k: p.text(*a, mock=True, **k)
    T(x + 1, y + 3.0, "IN  MPD · NOTE 36 · CH10", 1.4, "#7b6cff", 700, "start", 0.3)
    rows = [("MUTE 1", "DR MUTE", "ON/OFF"), ("REC 1", "DR NEW", "ONCE"), ("FADER 1", "DR DENS", ""),
            ("PAD 13", "NEW ALL", "ONCE"), ("PAD 3", "FILL", "HOLD"), ("BANK >", "GENRE", "STEP"), ("KNOB 8C", "FREE", "")]
    for i, (a, b, c) in enumerate(rows):
        yy = y + 6.6 + i * 2.75
        T(x + 1, yy, a, 1.3, gpanel.DIM, 700, "start", 0.25)
        T(x + w * 0.36, yy, b, 1.3, "#7b6cff" if i == 3 else gpanel.TXT, 700, "start", 0.25)
        T(x + w - 1, yy, c, 1.3, gpanel.DIM, 700, "end", 0.25)
if not gpanel.preview(p, "MapX"):
    open(os.path.join(gpanel.ROOT, "res", "MapX.svg"), "w").write(gpanel.svg(p))
    hdr = ["// Generated by tools/mapx_panel.py - do not edit", "// Rack pixels (1 HP = 15 px).", "#pragma once",
           gpanel.layout(p, None, "mapxl"), ""]
    open(os.path.join(gpanel.ROOT, "src", "MapXLayout.hpp"), "w").write("\n".join(hdr))
    print(f"MapX: {p.hp} HP, written res/MapX.svg src/MapXLayout.hpp")
